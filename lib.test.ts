describe('sanitize', () => {
  test('spaces and punctuation → dashes, trimmed', () => {
    expect(sanitize('Hello, World!')).toBe('Hello-World')
  })
  test('leading/trailing separators stripped', () => {
    expect(sanitize('  --foo--  ')).toBe('foo')
  })
  test('caps at 60 chars', () => {
    expect(sanitize('a'.repeat(100)).length).toBe(60)
  })
  test('empty-ish input falls back to "topic"', () => {
    expect(sanitize('')).toBe('topic')
    expect(sanitize('!!!')).toBe('topic')
  })
  // The bug this suite exists for: \w is ASCII-only, so EVERY non-Latin name used to
  // sanitize to the empty string and then to the constant 'topic' — one shared
  // directory, and therefore one shared outbox, for every such topic on a
  // deployment. Found in production when a transcript generated in خلاصه یوتیوب was
  // delivered into پک کادو.
  test('non-Latin scripts survive instead of collapsing to "topic"', () => {
    expect(sanitize('خلاصه یوتیوب')).toBe('خلاصه-یوتیوب')
    expect(sanitize('پک کادو')).toBe('پک-کادو')
    expect(sanitize('שלום')).toBe('שלום')
    expect(sanitize('привет')).toBe('привет')
    expect(sanitize('日本語')).toBe('日本語')
    expect(sanitize('ภาษาไทย')).toBe('ภาษาไทย')
  })
  test('two different non-Latin names do not collide', () => {
    expect(sanitize('خلاصه یوتیوب')).not.toBe(sanitize('پک کادو'))
  })
  // Devanagari vowel signs are \p{M}. Excluding marks would give ह-न-द here, and two
  // Hindi names differing only in their matras would still merge.
  test('combining marks are kept, so mark-using scripts stay distinct', () => {
    expect(sanitize('हिन्दी')).toBe('हिन्दी')
    expect(sanitize('हिन्दी')).not.toBe(sanitize('हनदी'))
  })
  // NFC, not NFKD: marks are kept above, so decomposing would hand the accent back.
  test('accents are preserved rather than folded away', () => {
    expect(sanitize('café')).toBe('café')
    expect(sanitize('naïve')).toBe('naïve')
  })
  // join(SESSIONS_BASE, '..') resolves to the PARENT of the sessions base. Both '.'
  // and '-' are legal in a name, so a dot-only name used to pass straight through.
  test('a dot-only name cannot escape the sessions base', () => {
    expect(sanitize('..')).toBe('topic')
    expect(sanitize('.')).toBe('topic')
    expect(sanitize('...')).toBe('topic')
    expect(sanitize('./..')).toBe('topic')
  })
  test('a leading dot cannot make a hidden directory', () => {
    expect(sanitize('.hidden')).toBe('hidden')
  })
  test('a slash is still stripped, so no name spans two path segments', () => {
    expect(sanitize('a/../b')).toBe('a-..-b')
  })
})

