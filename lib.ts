export function parseIdList(s: string | undefined): Set<string> {
  return new Set((s || '').split(',').map(x => x.trim()).filter(Boolean))
}

export function keyFor(chatId: number | string, threadId: number | undefined): string {
  return `${chatId}:${threadId ?? 'main'}`
}

// A short, filesystem-safe tag for one topic, used to give it its own inbox and
// outbox inside a directory it SHARES with another topic (a fork). Derived from the
// topic key's last segment — the thread id, or `main` — because that is already the
// thing that distinguishes two topics in one chat.
export function topicTag(key: string): string {
  const last = key.split(':').pop() || 'main'
  return `t-${last.replace(/[^\w-]+/g, '')}`
}

// A filesystem-safe directory name for one topic. Unicode-aware on purpose: `\w`
// is ASCII-only, so the previous version mapped EVERY letter of a Persian, Arabic,
// Hebrew, Cyrillic, CJK, Devanagari or Thai name to `-`, trimmed the result to the
// empty string, and handed back the constant `topic` — giving every non-Latin topic
// on a deployment ONE shared cwd, and therefore one shared outbox.
//
// Three details that are easy to get wrong and were:
//   NFC, not NFKD. Marks are kept (below), so decomposing first would hand back the
//     accent we just promised to keep: NFKD turns `café` into `cafe` + a combining
//     acute, and the mark then survives the filter anyway.
//   \p{M} is in the KEEP class because Devanagari vowel signs are marks. Without it
//     `हिन्दी` collapses to `ह-न-द` — still mangled, and two Hindi names differing
//     only in their matras still collide.
//   A name with no letter or digit at all is refused. `.` and `..` are otherwise
//     passed through untouched (both `.` and `-` are legal here), and
//     `join(SESSIONS_BASE, '..')` resolves to the PARENT of the sessions base.
// `/` is neither letter, number nor mark, so path traversal stays blocked.
// What a stored turn was ACTUALLY about, with two kinds of scaffolding removed.
//
// A transcript's first user turn is what /sessions labels a session with, and it is
// very often not something the user typed:
//
//   OURS. Every prompt reaches the model wrapped by frameUserMessage — and possibly
//   behind a files preamble, a fork's shared-directory note, or a carried background
//   result, each tagged `[xesious:<nonce>]`. Labelling a session with our own framing
//   ("[xesious:cfe601…] message from Ada, id 424242: …") tells the user nothing, and a
//   session whose first turn is only a preamble gets a label about outbox directories.
//
//   THE HARNESS'S. Claude Code injects `<local-command-caveat>`, `<command-name>`,
//   `<system-reminder>`, `<bash-input>` and friends as user turns. The reported case
//   was a session titled "<local-command-caveat>Caveat: The messages below were
//   generated by the user whil" — scaffolding, verbatim, as the name of a conversation.
//
// Returns '' when nothing but scaffolding is left, so the caller can move on to the
// next turn instead of showing an empty or meaningless label.
const XESIOUS_TAG = /\[xesious:[0-9a-f]+\]/i
// Everything after the LAST "message from …:" marker is the text the user actually
// sent; the preambles all sit above it. Non-greedy up to the first colon that ends
// the line or is followed by a space, so a colon INSIDE the message ("note: do X")
// is not mistaken for the end of the attribution.
const XESIOUS_SPEECH = /\[xesious:[0-9a-f]+\] message from [^\n]*?:(?:\n|[ \t]+)/gi
const HARNESS_BLOCKS = [
  /<local-command-caveat>[\s\S]*?<\/local-command-caveat>/gi,
  /<system-reminder>[\s\S]*?<\/system-reminder>/gi,
  /<command-(?:name|message|args)>[\s\S]*?<\/command-(?:name|message|args)>/gi,
  /<local-command-(?:stdout|stderr)>[\s\S]*?<\/local-command-(?:stdout|stderr)>/gi,
  /<bash-(?:input|stdout|stderr)>[\s\S]*?<\/bash-(?:input|stdout|stderr)>/gi,
  // An unterminated block — the transcript was truncated, or the tag is one we have
  // not seen. Dropping to end-of-text is right either way: what follows is scaffolding.
  /<(?:local-command|system-reminder|command|bash)-?[a-z]*>[\s\S]*$/gi,
]
export function transcriptSpeech(text: string): string {
  let out = text
  const marks = [...out.matchAll(XESIOUS_SPEECH)]
  if (marks.length) {
    const last = marks[marks.length - 1]
    out = out.slice((last.index ?? 0) + last[0].length)
  } else if (XESIOUS_TAG.test(out)) {
    // Tagged, but not speech: a files preamble, a fork note, a carried background
    // result. None of them is something the user said.
    return ''
  }
  for (const re of HARNESS_BLOCKS) out = out.replace(re, ' ')
  return out.replace(/\s+/g, ' ').trim()
}

export function sanitize(name: string): string {
  const s = name.normalize('NFC')
    .replace(/[^\p{L}\p{N}\p{M}._-]+/gu, '-')
    .replace(/^[-.]+|-+$/g, '')
    .slice(0, 60)
    .replace(/-+$/, '')
  return /[\p{L}\p{N}]/u.test(s) ? s : 'topic'
}

export function encodeCwd(dir: string): string {
  return dir.replace(/[^a-zA-Z0-9]/g, '-')
}

// Parse the args of /sessions or /import into directories. Space-separated, or
// comma/newline-separated when a path itself contains spaces.
export function parseDirs(text: string): string[] {
  const i = text.indexOf(' ')
  if (i === -1) return []
  const rest = text.slice(i + 1).trim()
  if (!rest) return []
  const parts = (rest.includes('\n') || rest.includes(',')) ? rest.split(/[\n,]+/) : rest.split(/\s+/)
  return parts.map(p => p.trim()).filter(Boolean)
}

// The path /get was given, or '' when there is none. It used to be whatever followed
// the first space — and a bare `/get` has no space, so that was the command itself,
// which a `startsWith('/')` check turned away along with every absolute path
// (reported 2026-09-25). Quotes are a shell habit and `~` means home, as in a shell.
export function getPathArg(text: string, home: string): string {
  const i = text.search(/\s/)
  let arg = i === -1 ? '' : text.slice(i + 1).trim()
  if (/^(["']).+\1$/.test(arg)) arg = arg.slice(1, -1)
  if (arg === '~' || arg.startsWith('~/')) arg = home + arg.slice(1)
  return arg
}

