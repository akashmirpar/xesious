// TEMPORARY — REMOVE WHEN TELEGRAM FIXES THE BUGS BELOW.
//
// A rich message renders its plain paragraphs in a different font and line height
// from every other message in the chat, so a thread that mixes the two looks
// inconsistent, and rich text is broken outright for right-to-left scripts:
//   https://bugs.telegram.org/c/63677  taller bubbles / extra line spacing than the
//     same text sent normally (Desktop + iOS). CLOSED 2026-07-16 with no explanation
//     and no fix — so do NOT read "closed" here as "safe to remove this workaround".
//   https://bugs.telegram.org/c/62776  iOS ignores the user's Settings > Appearance
//     text size for rich text, plus odd padding and line spacing. Open.
//   https://bugs.telegram.org/c/62877  RTL (Persian/Arabic): table alignment breaks
//     and list bullets sit on the wrong side, on Android but not Desktop. Still open
//     (re-checked 2026-08-28, Android 12.8.2), but it is scoped to TABLES and
//     FORMULAS — not to rich text as such. It used to gate every RTL message onto
//     the legacy path via a hasRtl() check here; that check is gone (2026-08-28),
//     because a contains-any-RTL-character test downgraded an entire English answer
//     that quoted one Arabic word, and it permanently denied Persian, Arabic and
//     Hebrew users headings, collapsibles, task lists and spoilers that render
//     correctly for them today. RTL tables are the accepted cost.
// Verified here 2026-08-01: the SAME unformatted sentence sent through
// sendRichMessage and through sendMessage came back visibly different.
//
// So rich is spent only where it buys something MarkdownV2 genuinely cannot
// express — a table, a collapsible, a formula, a task list, a footnote, a spoiler.
// Ordinary prose, bold, italic, links, quotes, bullet lists and code blocks all
// render fine the old way and now stay there; so do headings, which MarkdownV2
// turns into bold. Once the rendering is consistent, delete needsRich and send
// everything as rich again.
//
// Detectors run on the text with code stripped out: a shell snippet is full of
// pipes and dollar signs, and matching those would send every command to the rich
// path for a table and a formula that aren't there.
const stripCode = (s: string) => s.replace(/```[\s\S]*?```/g, '').replace(/`[^`\n]+`/g, '')
const RICH_ONLY = [
  // Table: a header line, then a delimiter row on the VERY next line that itself
  // contains a pipe. Both conditions matter — GFM breaks a table at a blank line,
  // and a bare "---" under a line that merely happens to contain a pipe is a setext
  // heading, not a table. Telegram agrees: it parses that as a heading.
  /^[^\n]*\|[^\n]*\n(?=[^\n]*\|)[ \t:|-]*-[ \t:|-]*$/m,
  /<details|<summary|<tg-/i,                            // collapsible and custom blocks
  /\$\$[\s\S]+?\$\$|```math/,                           // display formula
  /\$[^$\n]*[\\^_{}][^$\n]*\$/,                         // inline formula (LaTeX-ish, not "$5")
  /^\s*[-*+]\s+\[[ xX]\]\s/m,                           // task list (MarkdownV2 drops the checkbox)
  /^\s*\[\^[^\]]+\]:/m,                                 // footnote definition
  /==[^=\n]+==|\|\|[^|\n]+\|\||<sub>|<sup>/i,           // marked, spoiler, sub/sup
]
export const needsRich = (s: string) => { const t = stripCode(s); return RICH_ONLY.some(re => re.test(t)) }

// Cut `text` down to at most `budget` characters for use as a file caption, ending
// on a structure boundary rather than mid-token.
//
// The old version was a flat `text.slice(0, 900)`, which is why the preview of a
// long answer routinely ended halfway through a word, a link, a table row, or —
// worst — inside an unterminated ``` fence. That last one is not cosmetic: an
// unbalanced entity makes Telegram REJECT the whole caption, and a rejected caption
// used to mean no file at all.
//
// Boundaries in preference order: paragraph, line, word. A boundary is only taken
// if it leaves at least 40% of the budget, so a single very long paragraph still
// gets a useful preview instead of being cut back to nothing.
export function previewCut(text: string, budget: number): string {
  let out = text.trimEnd()
  if (text.length > budget) {
    const head = text.slice(0, budget)
    const floor = Math.floor(budget * 0.4)
    let cut = budget
    for (const sep of ['\n\n', '\n', ' ']) {
      const at = head.lastIndexOf(sep)
      if (at >= floor) { cut = at; break }
    }
    out = text.slice(0, cut).trimEnd()
  }
  // An odd number of fences means the last one is still open. Close it rather than
  // dropping back to it: closing keeps the lines we already decided to show, and
  // an unbalanced fence is the specific thing Telegram refuses to parse.
  // Runs on the untruncated path too — a model can emit an unbalanced fence itself.
  if ((out.match(/^\s*```/gm) || []).length % 2 === 1) out += '\n```'
  return out
}

// ---------------------------------------------------------------------------
// speech — turning an answer into something that SOUNDS like prose
//
// stripMd is not usable for this and must not be changed to be: it is shared with
// the text path (the sendMessage fallback, captions, the file preview), where
// inserting pauses or rewriting headings would corrupt messages that have nothing to
// do with voice. So speech gets its own pass, applied only on the TTS path.
//
// The reported symptom was "the speech is like a continuous text without much wait
// or difference for titles". The cause is mechanical: stripMd removes a heading's
// `##` and keeps its words, and a heading has no terminal punctuation, so
// `## Results` + `The tests pass` reaches the engine as one sentence — every TTS
// engine phrases on punctuation, not on newlines. Bullets are the mirror image:
// stripMd has no rule for `- ` at all, so the marker is read out or swallowed and
// the beat it stands for is never produced.
// ---------------------------------------------------------------------------

// The speakers offered on the keyboard.
